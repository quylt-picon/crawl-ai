"""Preset test harness for Product Manual Finder + Web Search Finder.

Runs one preset per brand (Panasonic / LG / Sony) through both pipelines and,
for Web Search Finder, every combination of {SerpAPI, Grounded} x {with-site,
no-site}. Consumes the live SSE stream for each job to capture queries, sources,
manuals and per-step timing, then fetches the canonical result.

Output: a JSON dump of all runs to output/preset_test_results.json. The Excel +
Markdown reports are generated by a separate step from that JSON.
"""
from __future__ import annotations

import json
import time
from datetime import datetime, timezone
from typing import Any

import requests

BASE = "http://localhost:8080"
RESULTS_PATH = "output/preset_stability_results.json"

# How many times to repeat the whole 15-run matrix, to measure run-to-run
# stability (the same input can return different links across runs).
N_ITERATIONS = 3

# One preset per brand (picked from frontend/public/presets.json).
PRESETS = [
    {
        "brand": "Panasonic",
        "website_url": "https://www.panasonic.com/vn",
        "product_name": "Máy giặt cửa trên",
        "product_code": "NA-F85S11BRV",
    },
    {
        "brand": "LG",
        "website_url": "https://www.lg.com/vn",
        "product_name": "Máy giặt lồng ngang",
        "product_code": "FV1412S3B",
    },
    {
        "brand": "Sony",
        "website_url": "https://www.sony.com.vn/",
        "product_name": "Tai nghe chống ồn",
        "product_code": "WF-1000XM6",
    },
]

CRAWL_TIMEOUT = 360      # seconds, wall-clock per crawl run
WEBSEARCH_TIMEOUT = 180  # seconds, wall-clock per web-search run


def _iter_sse(resp: requests.Response):
    """Yield (event_name, data_dict) tuples from an SSE response stream."""
    event_name = "message"
    data_lines: list[str] = []
    for raw in resp.iter_lines(decode_unicode=True):
        if raw is None:
            continue
        line = raw
        if line == "":  # dispatch on blank line
            if data_lines:
                payload = "\n".join(data_lines)
                try:
                    data = json.loads(payload)
                except json.JSONDecodeError:
                    data = {"_raw": payload}
                yield event_name, data
            event_name = "message"
            data_lines = []
            continue
        if line.startswith(":"):  # comment / ping
            continue
        if line.startswith("event:"):
            event_name = line[len("event:"):].strip()
        elif line.startswith("data:"):
            data_lines.append(line[len("data:"):].lstrip())


def _consume(start_path: str, payload: dict[str, Any], timeout: int) -> dict[str, Any]:
    """POST to a start endpoint, stream its SSE feed, then fetch the result."""
    t0 = time.monotonic()
    started_at = datetime.now(timezone.utc).isoformat()

    record: dict[str, Any] = {
        "started_at": started_at,
        "progress": [],          # list of {step,status,message,t}
        "log_count": 0,
        "queries": [],
        "sources": [],
        "manuals": [],
        "summary": None,
        "reason": None,
        "completion": None,
        "error": None,
        "elapsed_s": None,
        "timed_out": False,
    }

    try:
        r = requests.post(f"{BASE}{start_path}", json=payload, timeout=30)
        r.raise_for_status()
        job = r.json()
    except Exception as exc:  # noqa: BLE001
        record["error"] = f"start failed: {exc}"
        record["elapsed_s"] = round(time.monotonic() - t0, 1)
        return record

    job_id = job["job_id"]
    stream_url = job["stream_url"]
    record["job_id"] = job_id

    try:
        with requests.get(f"{BASE}{stream_url}", stream=True, timeout=(10, timeout)) as resp:
            resp.raise_for_status()
            for event_name, data in _iter_sse(resp):
                if time.monotonic() - t0 > timeout:
                    record["timed_out"] = True
                    break
                if event_name == "progress":
                    record["progress"].append(
                        {
                            "step": data.get("step"),
                            "status": data.get("status"),
                            "message": data.get("message"),
                            "t": round(time.monotonic() - t0, 1),
                        }
                    )
                    d = data.get("data") or {}
                    if isinstance(d, dict):
                        if d.get("queries"):
                            record["queries"] = d["queries"]
                        if d.get("sources"):
                            record["sources"] = d["sources"]
                        if d.get("manuals"):
                            record["manuals"] = d["manuals"]
                        if d.get("summary") is not None:
                            record["summary"] = d["summary"]
                        if d.get("reason") is not None:
                            record["reason"] = d["reason"]
                elif event_name == "log":
                    record["log_count"] += 1
                elif event_name == "completion":
                    record["completion"] = data
                    break
    except Exception as exc:  # noqa: BLE001
        record["error"] = f"stream error: {exc}"

    record["elapsed_s"] = round(time.monotonic() - t0, 1)

    # Fetch the canonical result (blocks until done; gives primary manual + inline).
    try:
        result_url = stream_url.replace("/stream/", "/result/")
        rr = requests.get(f"{BASE}{result_url}", timeout=timeout)
        if rr.ok:
            record["result"] = rr.json()
    except Exception as exc:  # noqa: BLE001
        record["result_error"] = str(exc)

    return record


def _default_model() -> str | None:
    """Mirror the UI: on mount it fetches /models and uses `res.default` as the
    selected model, which is then sent on every web-search request."""
    try:
        r = requests.get(f"{BASE}/api/websearch/models", timeout=30)
        r.raise_for_status()
        return r.json().get("default") or None
    except Exception as exc:  # noqa: BLE001
        print(f"  (could not fetch default model: {exc} — backend default applies)", flush=True)
        return None


def main() -> None:
    runs: list[dict[str, Any]] = []
    model = _default_model()
    print(f"Web-search model (as the UI sends it): {model!r}", flush=True)

    for it in range(1, N_ITERATIONS + 1):
        print(f"\n===== ITERATION {it}/{N_ITERATIONS} =====", flush=True)
        for p in PRESETS:
            brand = p["brand"]
            site = p["website_url"]
            name = p["product_name"].strip()
            code = p["product_code"].strip()

            # ── Product Manual Finder (crawl) — site required ──
            print(f"[it{it}][crawl] {brand} {code} ...", flush=True)
            rec = _consume(
                "/api/crawl/search",
                {"website_url": site, "product_name": name, "product_code": code},
                CRAWL_TIMEOUT,
            )
            runs.append(
                {
                    "iteration": it,
                    "function": "Product Manual Finder",
                    "brand": brand,
                    "product_name": name,
                    "product_code": code,
                    "site": site,
                    "mode": "crawl",
                    "use_serpapi": None,
                    "with_site": True,
                    "model": None,
                    **rec,
                }
            )
            _dump(runs)

            # ── Web Search Finder — 4 combos ──
            for use_serpapi in (True, False):
                for with_site in (True, False):
                    mode = "SerpAPI" if use_serpapi else "Grounded"
                    label = f"{mode} / {'with-site' if with_site else 'no-site'}"
                    print(f"[it{it}][websearch] {brand} {code} — {label} ...", flush=True)
                    body: dict[str, Any] = {
                        "product_name": name,
                        "product_code": code,
                        "use_serpapi": use_serpapi,
                    }
                    if model:
                        body["model"] = model
                    if with_site:
                        body["website_url"] = site
                    rec = _consume("/api/websearch/search", body, WEBSEARCH_TIMEOUT)
                    runs.append(
                        {
                            "iteration": it,
                            "function": "Web Search Finder",
                            "brand": brand,
                            "product_name": name,
                            "product_code": code,
                            "site": site if with_site else None,
                            "mode": mode,
                            "use_serpapi": use_serpapi,
                            "with_site": with_site,
                            "model": model,
                            **rec,
                        }
                    )
                    _dump(runs)

    print(f"\nDONE — {len(runs)} runs ({N_ITERATIONS} iterations) → {RESULTS_PATH}", flush=True)


def _dump(runs: list[dict[str, Any]]) -> None:
    with open(RESULTS_PATH, "w", encoding="utf-8") as fh:
        json.dump(runs, fh, ensure_ascii=False, indent=2)


if __name__ == "__main__":
    main()
